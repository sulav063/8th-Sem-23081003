SELECT MANAGER_ID,
       MIN(SALARY) AS SALARY
FROM HR.EMPLOYEES
WHERE MANAGER_ID IS NOT NULL
GROUP BY MANAGER_ID
HAVING MIN(SALARY) > 6000
ORDER BY SALARY DESC;
















